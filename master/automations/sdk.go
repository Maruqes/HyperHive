// Route is one master HTTP route, as reported by chi.Walk.
type Route struct {
	Method  string
	Pattern string
}

var (
	sdkMu          sync.RWMutex
	sdkDeclaration = declarationHeader + "interface HHApi {}\n"
	apiURL         = "http://127.0.0.1:9595"
	paramPattern   = regexp.MustCompile(`\{([^}:]+)(?::[^}]*)?\}`)
)

// excludedRoute keeps internal, streaming and wildcard routes out of the
// generated functions; hh.request still reaches any path.
func excludedRoute(route Route) bool {
	pattern := route.Pattern
	for _, prefix := range []string{"/support-internal", "/mcp", "/novnc", "/login", "/nots/register", "/static/", "/icon.png", "/sw.js"} {
		if strings.HasPrefix(pattern, prefix) {
			return true
		}
	}
	return strings.Contains(pattern, "*") || strings.HasSuffix(pattern, "/ws") || pattern == "/" || route.Method == "OPTIONS" || route.Method == "HEAD" || route.Method == "CONNECT" || route.Method == "TRACE"
}

func identifier(value string, upperFirst bool) string {
	var builder strings.Builder
	upper := upperFirst
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = builder.Len() > 0 || upperFirst
			continue
		}
		if builder.Len() == 0 && unicode.IsDigit(r) {
			builder.WriteRune('_')
		}
		if upper {
			builder.WriteRune(unicode.ToUpper(r))
			upper = false
		} else if builder.Len() == 0 && !upperFirst {
			builder.WriteRune(unicode.ToLower(r))
		} else {
			builder.WriteRune(r)
		}
	}
	return builder.String()
}

type sdkFunction struct {
	group, name, method, pattern, template string
	params                                 []string
}

func buildFunctions(routes []Route) []sdkFunction {
	seen := map[string]bool{}
	functions := []sdkFunction{}
	sort.Slice(routes, func(i, j int) bool {
		if routes[i].Pattern != routes[j].Pattern {
			return routes[i].Pattern < routes[j].Pattern
		}
		return routes[i].Method < routes[j].Method
	})
	for _, route := range routes {
		if excludedRoute(route) {
			continue
		}
		pattern := strings.TrimSuffix(route.Pattern, "/")
		segments := strings.Split(strings.Trim(pattern, "/"), "/")
		if len(segments) == 0 || segments[0] == "" || strings.Contains(segments[0], "{") {
			continue
		}
		function := sdkFunction{group: identifier(segments[0], false), method: route.Method, pattern: pattern}
		static := ""
		for _, segment := range segments[1:] {
			if !strings.Contains(segment, "{") {
				static += identifier(segment, true)
			}
		}
		used := map[string]bool{}
		function.template = paramPattern.ReplaceAllStringFunc(pattern, func(match string) string {
			name := identifier(paramPattern.FindStringSubmatch(match)[1], false)
			if name == "" || used[name] || name == "options" {
				name = fmt.Sprintf("p%d", len(function.params)+1)
			}
			used[name] = true
			function.params = append(function.params, name)
			return "${encodeURIComponent(String(" + name + "))}"
		})
		function.name = strings.ToLower(route.Method) + static
		if len(function.params) > 0 {
			parts := make([]string, len(function.params))
			for index, param := range function.params {
				parts[index] = identifier(param, true)
			}
			function.name += "By" + strings.Join(parts, "And")
		}
		key := function.group + "." + function.name
		for suffix := 2; seen[key]; suffix++ {
			key = fmt.Sprintf("%s.%s%d", function.group, function.name, suffix)
		}
		function.name = strings.TrimPrefix(key, function.group+".")
		seen[key] = true
		functions = append(functions, function)
	}
	return functions
}

const declarationHeader = `// Generated by the HyperHive master from its route table. Do not edit.
// Request and response bodies are untyped (any); see the HyperHive API docs.
interface HHRequestOptions {
  query?: Record<string, string | number | boolean | null | undefined>;
  body?: unknown;
  headers?: Record<string, string>;
  /** Defaults to 120000 ms. */
  timeoutMs?: number;
  signal?: AbortSignal;
}
interface HHContext {
  runId: string;
  automationId: string;
  automationName: string;
  trigger: "manual" | "condition";
  condition: string;
  /** Values the condition read when it fired, e.g. { "db.cpu": 97 }. */
  snapshot: Record<string, unknown>;
}
interface HHLog {
  info(...args: unknown[]): void;
  warn(...args: unknown[]): void;
  error(...args: unknown[]): void;
}
interface HHClient {
  /** Calls any master REST path (e.g. "/virsh/getallvms") with this run's token. */
  request<T = any>(method: string, path: string, options?: HHRequestOptions): Promise<T>;
  get<T = any>(path: string, options?: HHRequestOptions): Promise<T>;
  post<T = any>(path: string, body?: unknown, options?: HHRequestOptions): Promise<T>;
  put<T = any>(path: string, body?: unknown, options?: HHRequestOptions): Promise<T>;
  patch<T = any>(path: string, body?: unknown, options?: HHRequestOptions): Promise<T>;
  delete<T = any>(path: string, options?: HHRequestOptions): Promise<T>;
  /** One function per master route; path parameters are positional arguments. */
  api: HHApi;
}
interface HHAutomationArgs {
  ctx: HHContext;
  hh: HHClient;
  log: HHLog;
}
declare const hh: HHClient;
declare const ctx: HHContext;
declare const log: HHLog;
`

// GenerateSDK returns the TypeScript declarations and the ESM runtime module.
func GenerateSDK(routes []Route) (string, string) {
	functions := buildFunctions(routes)
	groups := map[string][]sdkFunction{}
	order := []string{}
	for _, function := range functions {
		if _, exists := groups[function.group]; !exists {
			order = append(order, function.group)
		}
		groups[function.group] = append(groups[function.group], function)
	}
	var declaration, runtime strings.Builder
	declaration.WriteString(declarationHeader)
	declaration.WriteString("interface HHApi {\n")
	runtime.WriteString(runtimeHeader)
	runtime.WriteString("export const api = {\n")
	for _, group := range order {
		fmt.Fprintf(&declaration, "  %s: {\n", group)
		fmt.Fprintf(&runtime, "  %s: {\n", group)
		for _, function := range groups[group] {
			args := []string{}
			for _, param := range function.params {
				args = append(args, param+": string | number")
			}
			args = append(args, "options?: HHRequestOptions")
			fmt.Fprintf(&declaration, "    /** %s %s */\n    %s<T = any>(%s): Promise<T>;\n", function.method, function.pattern, function.name, strings.Join(args, ", "))
			fmt.Fprintf(&runtime, "    %s: (%s) => request(%q, `%s`, options),\n", function.name, strings.Join(append(function.params, "options"), ", "), function.method, function.template)
		}
		declaration.WriteString("  };\n")
		runtime.WriteString("  },\n")
	}
	declaration.WriteString("}\n")
	runtime.WriteString("};\n\nexport const hh = { request, get, post, put, patch, delete: del, api };\n")
	return declaration.String(), runtime.String()
}

const runtimeHeader = `// Generated by the HyperHive master from its route table. Do not edit.
const base = process.env.HH_API_URL;
const token = process.env.HH_TOKEN;

export async function request(method, path, options = {}) {
  const url = new URL(path.startsWith("/") ? path : "/" + path, base);
  for (const [key, value] of Object.entries(options.query ?? {})) {
    if (value !== undefined && value !== null) url.searchParams.set(key, String(value));
  }
  const headers = { Authorization: "Bearer " + token, ...(options.headers ?? {}) };
  let body;
  if (options.body !== undefined) {
    if (typeof options.body === "string" || options.body instanceof Uint8Array) {
      body = options.body;
    } else {
      body = JSON.stringify(options.body);
      headers["Content-Type"] ??= "application/json";
    }
  }
  const signal = options.signal ?? AbortSignal.timeout(options.timeoutMs ?? 120000);
  const response = await fetch(url, { method, headers, body, signal });
  const text = await response.text();
  if (!response.ok) {
    const error = new Error(method + " " + path + " failed with " + response.status + ": " + text.slice(0, 2000));
    error.status = response.status;
    error.body = text;
    throw error;
  }
  const trimmed = text.trim();
  if ((response.headers.get("content-type") ?? "").includes("json") || trimmed.startsWith("{") || trimmed.startsWith("[")) {
    try {
      return JSON.parse(text);
    } catch {}
  }
  return text;
}
const get = (path, options) => request("GET", path, options);
const post = (path, body, options = {}) => request("POST", path, { ...options, body });
const put = (path, body, options = {}) => request("PUT", path, { ...options, body });
const patch = (path, body, options = {}) => request("PATCH", path, { ...options, body });
const del = (path, options) => request("DELETE", path, options);

`

