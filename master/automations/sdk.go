// Configure generates the SDK from the master's routes and writes the runtime
// files into the workspace. port is the master API port used by scripts.
func Configure(port string, routes []Route) error {
	declaration, runtime := GenerateSDK(routes)
	sdkMu.Lock()
	sdkDeclaration = declaration
	apiURL = "http://127.0.0.1:" + port
	sdkMu.Unlock()
	if err := EnsureWorkspace(); err != nil {
		return err
	}
	files := map[string]string{
		filepath.Join(runtimeDir(), "hh.d.ts"):     declaration,
		filepath.Join(runtimeDir(), "hh.mjs"):      runtime,
		filepath.Join(runtimeDir(), "runtime.mjs"): runnerModule,
		filepath.Join(Dir(), "tsconfig.json"):      workspaceTSConfig,
	}
	for path, content := range files {
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}
	return nil
}

// Declaration returns the generated hh.d.ts for editors.
func Declaration() string {
	sdkMu.RLock()
	defer sdkMu.RUnlock()
	return sdkDeclaration
}

func masterURL() string {
	sdkMu.RLock()
	defer sdkMu.RUnlock()
	return apiURL
}
